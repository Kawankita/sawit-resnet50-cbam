# **Fungsi kustom Normalisasi Z-Score ImageNet sesuai rumus: (input - mean) / std**
def imagenet_zscore_normalize(img):
    # **Mengubah rentang piksel citra dari [0, 255] menjadi bilangan pecahan [0.0, 1.0]**
    img = tf.cast(img, tf.float32) / 255.0
