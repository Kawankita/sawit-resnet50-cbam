# --- 1. IMPLEMENTASI CHANNEL ATTENTION MODULE ---
def channel_attention_module(x, ratio=16, name_prefix=""):
    # **Mengambil jumlah channel dari tensor input (axis terakhir / kedalaman fitur)**
    channels = x.shape[-1]
    # **Global Average Pooling untuk merangkum informasi spasial rata-rata tiap channel**
    gap = layers.GlobalAveragePooling2D(name=f"{name_prefix}_ca_gap")(x)
    # **Global Max Pooling untuk merangkum fitur visual paling dominan pada tiap channel**
    gmp = layers.GlobalMaxPooling2D(name=f"{name_prefix}_ca_gmp")(x)

    # **Shared MLP (Multi-Layer Perceptron) dengan reduction ratio untuk efisiensi parameter**
    shared_dense_1 = layers.Dense(channels // ratio, activation='relu', kernel_initializer='he_normal', use_bias=True, name=f"{name_prefix}_ca_dense1")
    shared_dense_2 = layers.Dense(channels, kernel_initializer='he_normal', use_bias=True, name=f"{name_prefix}_ca_dense2")

    # **Melewatkan vektor GAP dan GMP melalui jaringan MLP berbagi bobot yang sama**
    gap_out = shared_dense_2(shared_dense_1(gap))
    gmp_out = shared_dense_2(shared_dense_1(gmp))

    # **Menjumlahkan kedua vektor representasi dan menerapkan fungsi aktivasi Sigmoid**
    attn = layers.Add(name=f"{name_prefix}_ca_add")([gap_out, gmp_out])
    attn = layers.Activation('sigmoid', name=f"{name_prefix}_ca_sigmoid")(attn)
    # **Mengubah dimensi (reshape) menjadi tensor 4D (1, 1, Channels) agar bisa dikalikan**
    attn = layers.Reshape((1, 1, channels), name=f"{name_prefix}_ca_reshape")(attn)
    # **Perkalian elemen (Element-wise multiplication) untuk menonjolkan channel penting**
    return layers.Multiply(name=f"{name_prefix}_ca_mul")([x, attn])

# --- 2. IMPLEMENTASI SPATIAL ATTENTION MODULE ---
def spatial_attention_module(x, kernel_size=7, name_prefix=""):
    # **Average Pooling di sepanjang axis channel untuk peta rata-rata spasial (1 channel)**
    avg_pool = layers.Lambda(lambda tensor: tf.reduce_mean(tensor, axis=-1, keepdims=True), name=f"{name_prefix}_sa_avg")(x)
    # **Max Pooling di sepanjang axis channel untuk peta tonjolan spasial dominan (1 channel)**
    max_pool = layers.Lambda(lambda tensor: tf.reduce_max(tensor, axis=-1, keepdims=True), name=f"{name_prefix}_sa_max")(x)

    # **Menggabungkan (Concatenate) kedua peta pooling menjadi tensor berkedalaman 2 channel**
    concat = layers.Concatenate(axis=-1, name=f"{name_prefix}_sa_concat")([avg_pool, max_pool])
    # **Konvolusi spasial dengan kernel 7x7 dan aktivasi Sigmoid untuk membuat Spatial Map**
    attn = layers.Conv2D(filters=1, kernel_size=kernel_size, strides=1, padding='same', activation='sigmoid', kernel_initializer='he_normal', use_bias=False, name=f"{name_prefix}_sa_conv")(concat)
    # **Perkalian elemen untuk memberikan bobot perhatian pada lokasi spasial buah sawit**
    return layers.Multiply(name=f"{name_prefix}_sa_mul")([x, attn])

# --- 3. GABUNGAN MODUL CBAM ---
def cbam_block(x, ratio=16, kernel_size=7, name_prefix=""):
    # **Urutan CBAM standar: Channel Attention diterapkan lebih dulu, disusul Spatial Attention**
    x = channel_attention_module(x, ratio=ratio, name_prefix=name_prefix)
    x = spatial_attention_module(x, kernel_size=kernel_size, name_prefix=name_prefix)
    return x

# --- 4. PEMBUATAN RESNET-50 MODIFIKASI (DENGAN CBAM DI SETIAP BLOCK) ---
def resnet_block_cbam(x, filters, stage, block, strides=(1, 1), use_conv_shortcut=False):
    # **Penamaan blok disamakan eksak dengan Keras ResNet50 standar untuk transfer bobot ImageNet**
    block_name = f"conv{stage}_block{block}"
    f1, f2, f3 = filters

    # **Jalur Shortcut (Skip Connection)**
    if use_conv_shortcut:
        # **Jika dimensi berubah, shortcut menggunakan konvolusi 1x1 untuk menyamakan bentuk**
        shortcut = layers.Conv2D(f3, kernel_size=(1, 1), strides=strides, name=f"{block_name}_0_conv")(x)
        shortcut = layers.BatchNormalization(name=f"{block_name}_0_bn")(shortcut)
    else:
        # **Jika dimensi sama, shortcut langsung meneruskan tensor identitas input asli**
        shortcut = x

    # **Jalur Utama - Konvolusi ke-1 (Bottleneck 1x1 untuk reduksi dimensi channel)**
    res = layers.Conv2D(f1, kernel_size=(1, 1), strides=strides, name=f"{block_name}_1_conv")(x)
    res = layers.BatchNormalization(name=f"{block_name}_1_bn")(res)
    res = layers.Activation('relu', name=f"{block_name}_1_relu")(res)

    # **Jalur Utama - Konvolusi ke-2 (Konvolusi spasial utama 3x3)**
    res = layers.Conv2D(f2, kernel_size=(3, 3), padding='same', name=f"{block_name}_2_conv")(res)
    res = layers.BatchNormalization(name=f"{block_name}_2_bn")(res)
    res = layers.Activation('relu', name=f"{block_name}_2_relu")(res)

    # **Jalur Utama - Konvolusi ke-3 (Bottleneck 1x1 untuk ekspansi kembali dimensi channel)**
    res = layers.Conv2D(f3, kernel_size=(1, 1), name=f"{block_name}_3_conv")(res)
    res = layers.BatchNormalization(name=f"{block_name}_3_bn")(res)

    # ** [KRUSIAL SKRIPSI] MENYISIPKAN CBAM DI AKHIR JALUR RESIDUAL SEBELUM OPERASI ADD **
    res = cbam_block(res, ratio=16, kernel_size=7, name_prefix=f"{block_name}_cbam")

    # **Operasi Add (Skip Connection): Menggabungkan fitur shortcut dengan jalur utama ber-attention**
    out = layers.Add(name=f"{block_name}_add")([shortcut, res])
    # **Aktivasi ReLU tahap akhir setelah operasi penjumlahan residual dilakukan**
    out = layers.Activation('relu', name=f"{block_name}_out")(out)
    return out

def build_resnet50_cbam_model(input_shape=(224, 224, 3), num_classes=3):
    # **Mendefinisikan layer Input tensor sesuai ukuran gambar sawit**
    inputs = layers.Input(shape=input_shape, name="input_1")

    # **Stage 1: Konvolusi awal 7x7 dan Max Pooling untuk menangkap fitur kasar (edges/blob)**
    x = layers.Conv2D(64, kernel_size=(7, 7), strides=(2, 2), padding='same', name="conv1_conv")(inputs)
    x = layers.BatchNormalization(name="conv1_bn")(x)
    x = layers.Activation('relu', name="conv1_relu")(x)
    x = layers.MaxPooling2D(pool_size=(3, 3), strides=(2, 2), padding='same', name="pool1_pool")(x)

    # **Stage 2 (3 Residual Blocks dengan CBAM)**
    x = resnet_block_cbam(x, [64, 64, 256], stage=2, block=1, strides=(1, 1), use_conv_shortcut=True)
    x = resnet_block_cbam(x, [64, 64, 256], stage=2, block=2)
    x = resnet_block_cbam(x, [64, 64, 256], stage=2, block=3)

    # **Stage 3 (4 Residual Blocks dengan CBAM)**
    x = resnet_block_cbam(x, [128, 128, 512], stage=3, block=1, strides=(2, 2), use_conv_shortcut=True)
    x = resnet_block_cbam(x, [128, 128, 512], stage=3, block=2)
    x = resnet_block_cbam(x, [128, 128, 512], stage=3, block=3)
    x = resnet_block_cbam(x, [128, 128, 512], stage=3, block=4)

    # **Stage 4 (6 Residual Blocks dengan CBAM)**
    x = resnet_block_cbam(x, [256, 256, 1024], stage=4, block=1, strides=(2, 2), use_conv_shortcut=True)
    for i in range(2, 7):
        x = resnet_block_cbam(x, [256, 256, 1024], stage=4, block=i)

    # **Stage 5 (3 Residual Blocks dengan CBAM - Layer ekstraksi fitur tingkat tinggi terakhir)**
    x = resnet_block_cbam(x, [512, 512, 2048], stage=5, block=1, strides=(2, 2), use_conv_shortcut=True)
    x = resnet_block_cbam(x, [512, 512, 2048], stage=5, block=2)
    x = resnet_block_cbam(x, [512, 512, 2048], stage=5, block=3)

    # --- CLASSIFICATION HEAD ---
    # **Global Average Pooling 2D mengubah feature map 3D menjadi vektor fitur 1D (2048 elemen)**
    x = layers.GlobalAveragePooling2D(name="cls_gap")(x)
    # **Fully Connected Layer (Dense) dengan 512 neuron dan aktivasi ReLU untuk representasi tingkat tinggi**
    x = layers.Dense(512, activation='relu', kernel_initializer='he_normal', name="cls_dense_512")(x)
    # **Dropout 50% untuk menonaktifkan neuron secara acak guna mencegah over-fitting pada data sawit**
    x = layers.Dropout(0.5, name="cls_dropout")(x)
    # **Layer output dengan 3 neuron dan aktivasi Softmax untuk probabilitas kelas kematangan sawit**
    outputs = layers.Dense(num_classes, activation='softmax', name="cls_output")(x)

    # **Membentuk objek model Keras Functional secara utuh**
    model = models.Model(inputs=inputs, outputs=outputs, name="ResNet50_CBAM_Kelapa_Sawit")

    # --- TRANSFER BOBOT IMAGENET AUTOMATIS ---
    # **Memuat bobot pre-trained ImageNet dari ResNet50 standar Keras (tanpa top classification layer)**
    print("[INFO] Memuat bobot ImageNet standar ke backbone ResNet-50+CBAM...")
    base_std = keras.applications.ResNet50(weights='imagenet', include_top=False, input_shape=input_shape)

    # **Menyalin bobot layer konvolusi dan batch norm standar ke arsitektur CBAM modifikasi kita**
    transferred = 0
    for layer in base_std.layers:
        try:
            target_layer = model.get_layer(layer.name)
            target_layer.set_weights(layer.get_weights())
            transferred += 1
        except ValueError:
            pass # Melewati layer yang tidak relevan atau layer CBAM baru
    print(f"[BERHASIL] Bobot ImageNet telah dipindahkan ke {transferred} layer tulang punggung model!")

    return model

# **Membuat instansiasi model ResNet50+CBAM dan menampilkan ringkasan arsitekturnya**
model_sawit = build_resnet50_cbam_model(input_shape=(224, 224, 3), num_classes=len(CLASSES))
